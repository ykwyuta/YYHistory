pub fn find(id: &str) -> Option<&'static Talk> {
    TALKS.iter().find(|t| t.person == id)
}

/// 人物の会話の場面の数（会話が無ければ、話のページの数）
pub fn pages(i: usize) -> usize {
    match find(PEOPLE[i].id) {
        Some(t) => t.asks.len() + 2,
        None => PEOPLE[i].lines.len(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::history::person_index;

    #[test]
    fn talks_belong_to_real_people() {
        let mut seen = std::collections::HashSet::new();
        for t in TALKS {
            assert!(seen.insert(t.person), "duplicate {}", t.person);
            assert!(person_index(t.person).is_some(), "{}", t.person);
            assert!((2..=5).contains(&t.asks.len()), "{}", t.person);
            for a in t.asks {
                assert!(a.q.ends_with('？'), "{}", a.q);
                // スマートフォンでも読める長さ
                assert!(a.a.chars().count() <= 220, "{} is too long", a.q);
            }
        }
    }
}
