//! 人物との会話：探偵が質問し、人物が気持ちをまじえて答える。
//!
//! 起きたこと（年・場所・行い）は史料に合わせる。気持ちや言い回しは、
//! 史料や伝記に伝わる人柄をもとに想像して書く（画面にもそう示す）。
//! 人物は、探偵が未来から来たことを知らない。自分の未来のことは話さない。
//!
//! 会話の場面の番号：0 は声をかけたところ、1〜 は質問への答え、最後は別れぎわ。
//! なぜ？ノートは `notes::Attach::Person(id, 場面の番号)` で結びつける。
use crate::history::PEOPLE;

pub struct Ask {
    /// 探偵の質問
    pub q: &'static str,
    /// 答える前のしぐさ（ト書き。無ければ空）
    pub how: &'static str,
    /// 人物の答え
    pub a: &'static str,
}

pub struct Talk {
    pub person: &'static str,
    /// 吹き出しに出す呼び名
    pub who: &'static str,
    /// 近づいたときの様子（ト書き）
    pub scene: &'static str,
    /// 声をかけたときの、人物の第一声
    pub greet: &'static str,
    pub asks: &'static [Ask],
    /// 別れぎわのひとこと
    pub bye: &'static str,
}

macro_rules! ask {
    ($q:literal, $how:literal, $a:literal) => {
        Ask {
            q: $q,
            how: $how,
            a: $a,
        }
    };
}

