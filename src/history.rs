//! 時代・場所・人物・出来事のデータ。
//!
//! 年は歴史学の数え方（負の数＝紀元前、0年は無い）。
//! 日本の和暦の月日は当時の暦（旧暦）のまま書き、西暦は年だけを添える。
//! 地図の座標（0〜1）は位置関係を示す概略で、測量に基づくものではない。
//! 人物の「言葉」は、史料に基づく事実を一人称で紹介する教材用の再構成であり、
//! 「」で示した史料からの引用を除いて、実際の発言ではない。

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    Palace,
    Temple,
    Market,
    Gate,
    Forum,
    Theater,
    House,
    Bridge,
    Hill,
    Castle,
    Church,
    Fortress,
    Hall,
    Water,
}

/// 地図の地形。座標は 0〜1（x は東へ、y は南へ）
pub enum Feature {
    /// 海・湖（多角形）
    Water(&'static [(f32, f32)]),
    /// 陸地（水の上に描く多角形）
    Land(&'static [(f32, f32)]),
    /// 川（折れ線と幅）
    River(&'static [(f32, f32)], f32),
    /// 丘（中心と半径）
    Hill(f32, f32, f32),
    /// 城壁・堀（閉じた折れ線）
    Wall(&'static [(f32, f32)]),
    /// 条坊などの碁盤目（x0, y0, x1, y1, 東西の数, 南北の数）
    Grid(f32, f32, f32, f32, u8, u8),
    /// 街道・堤道（折れ線）
    Road(&'static [(f32, f32)]),
    /// 地名の注記（文字, x, y）
    Label(&'static str, f32, f32),
}

pub struct Place {
    pub id: &'static str,
    pub name: &'static str,
    pub kind: Kind,
    pub x: f32,
    pub y: f32,
    pub desc: &'static str,
}

pub struct Era {
    pub id: &'static str,
    pub name: &'static str,
    pub period: &'static str,
    pub years: &'static str,
    /// 時代の始まりの年（一覧は年代順に並べる）
    #[allow(dead_code)]
    pub year: i32,
    pub area: &'static str,
    pub lon: f32,
    pub lat: f32,
    /// 世界地図での名札のずらし（画面座標）
    pub tag: (f32, f32),
    pub intro: &'static str,
    /// 地図の地色（紙・陸）
    pub tint: [f32; 4],
    pub features: &'static [Feature],
    pub places: &'static [Place],
    /// 道でつながる場所（places の番号）
    pub roads: &'static [(usize, usize)],
    pub start: usize,
    pub map_note: &'static str,
}

pub struct Person {
    pub id: &'static str,
    pub era: usize,
    pub place: &'static str,
    pub name: &'static str,
    pub native: &'static str,
    pub life: &'static str,
    pub role: &'static str,
    pub bio: &'static str,
    pub lines: &'static [&'static str],
    pub source: &'static str,
}

pub struct Event {
    pub id: &'static str,
    pub era: usize,
    pub place: &'static str,
    /// 時代の始まりの年（一覧は年代順に並べる）
    #[allow(dead_code)]
    pub year: i32,
    /// 並べ替え用の月日（月×100＋日。日が不明なら0）
    pub md: u16,
    pub date: &'static str,
    pub title: &'static str,
    pub body: &'static [&'static str],
    pub people: &'static [&'static str],
    pub source: &'static str,
}

