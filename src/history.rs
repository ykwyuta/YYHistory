/// アカシックレコードの試練の問題（四択）
pub struct Quiz {
    pub era: usize,
    pub q: &'static str,
    pub choices: [&'static str; 4],
    pub answer: usize,
    /// 答えた後に示す解説
    pub note: &'static str,
}

/// 試練に全問正解すると得られる、その時代にゆかりのある実在の品
pub struct Treasure {
    pub era: usize,
    pub name: &'static str,
    pub desc: &'static str,
    pub source: &'static str,
}

macro_rules! quiz {
    ($era:expr, $q:literal, [$a:literal, $b:literal, $c:literal, $d:literal], $ans:expr, $note:literal) => {
        Quiz {
            era: $era,
            q: $q,
            choices: [$a, $b, $c, $d],
            answer: $ans,
            note: $note,
        }
    };
}

