macro_rules! place {
    ($id:literal, $name:literal, $kind:ident, $x:expr, $y:expr, $desc:literal) => {
        Place {
            id: $id,
            name: $name,
            kind: Kind::$kind,
            x: $x,
            y: $y,
            desc: $desc,
        }
    };
}

