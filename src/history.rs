pub fn place_index(era: usize, id: &str) -> Option<usize> {
    ERAS[era].places.iter().position(|p| p.id == id)
}

pub fn person_index(id: &str) -> Option<usize> {
    PEOPLE.iter().position(|p| p.id == id)
}

pub fn event_index(id: &str) -> Option<usize> {
    EVENTS.iter().position(|e| e.id == id)
}

/// 出来事を年代順に並べたときの鍵
pub fn event_key(i: usize) -> (i32, u16) {
    (EVENTS[i].year, EVENTS[i].md)
}

/// 時代順の人物一覧（図鑑の番号の順）
pub fn people_order() -> Vec<usize> {
    let mut v: Vec<usize> = (0..PEOPLE.len()).collect();
    v.sort_by_key(|i| (PEOPLE[*i].era, *i));
    v
}

/// 年代順の出来事一覧
pub fn chronology() -> Vec<usize> {
    let mut v: Vec<usize> = (0..EVENTS.len()).collect();
    v.sort_by_key(|i| event_key(*i));
    v
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn data_is_consistent() {
        let mut ids = std::collections::HashSet::new();
        for p in PEOPLE {
            assert!(ids.insert(p.id), "duplicate person {}", p.id);
            assert!(
                place_index(p.era, p.place).is_some(),
                "person place {}",
                p.id
            );
            assert!(!p.lines.is_empty());
        }
        for e in EVENTS {
            assert!(ids.insert(e.id), "duplicate event {}", e.id);
            assert!(
                place_index(e.era, e.place).is_some(),
                "event place {}",
                e.id
            );
            assert_ne!(e.year, 0);
            for p in e.people {
                let i = person_index(p).unwrap_or_else(|| panic!("event person {p}"));
                assert_eq!(PEOPLE[i].era, e.era, "{} in {}", p, e.id);
            }
        }
        assert!(ERAS.windows(2).all(|w| w[0].year < w[1].year));
        for (k, era) in ERAS.iter().enumerate() {
            assert!(era.start < era.places.len());
            for (a, b) in era.roads {
                assert!(*a < era.places.len() && *b < era.places.len());
            }
            // every place is reachable from the start
            let mut seen = vec![false; era.places.len()];
            let mut stack = vec![era.start];
            while let Some(n) = stack.pop() {
                if std::mem::replace(&mut seen[n], true) {
                    continue;
                }
                for (a, b) in era.roads {
                    if *a == n {
                        stack.push(*b);
                    }
                    if *b == n {
                        stack.push(*a);
                    }
                }
            }
            assert!(seen.iter().all(|s| *s), "era {} disconnected", era.id);
            assert!(PEOPLE.iter().any(|p| p.era == k));
            assert!(EVENTS.iter().any(|e| e.era == k));
            for p in era.places {
                assert!((0. ..=1.).contains(&p.x) && (0. ..=1.).contains(&p.y));
            }
        }
    }
}
