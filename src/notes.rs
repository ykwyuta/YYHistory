/// 出来事のノート
pub fn for_event(id: &str) -> Vec<usize> {
    (0..NOTES.len())
        .filter(|i| NOTES[*i].attach == Attach::Event(id_static(id)))
        .collect()
}

/// 人物の話のページのノート
pub fn for_person(id: &str, page: usize) -> Vec<usize> {
    (0..NOTES.len())
        .filter(|i| matches!(NOTES[*i].attach, Attach::Person(p, k) if p == id && k == page))
        .collect()
}

/// 人物のすべてのノート（図鑑の説明用）
pub fn for_person_all(id: &str) -> Vec<usize> {
    (0..NOTES.len())
        .filter(|i| matches!(NOTES[*i].attach, Attach::Person(p, _) if p == id))
        .collect()
}

fn id_static(id: &str) -> &'static str {
    EVENTS.iter().map(|e| e.id).find(|e| *e == id).unwrap_or("")
}

/// ノートの時代
pub fn era(i: usize) -> usize {
    match NOTES[i].attach {
        Attach::Event(id) => EVENTS[event_index(id).unwrap()].era,
        Attach::Person(id, _) => PEOPLE[person_index(id).unwrap()].era,
    }
}

/// ノートの場面の名前（図鑑のヒント用）
pub fn scene(i: usize) -> String {
    match NOTES[i].attach {
        Attach::Event(id) => format!("出来事「{}」", EVENTS[event_index(id).unwrap()].title),
        Attach::Person(id, _) => format!("{}の話", PEOPLE[person_index(id).unwrap()].name),
    }
}

pub fn index(id: &str) -> Option<usize> {
    NOTES.iter().position(|n| n.id == id)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn notes_are_attached_to_real_scenes() {
        let mut ids = std::collections::HashSet::new();
        for n in NOTES {
            assert!(ids.insert(n.id), "duplicate note {}", n.id);
            match n.attach {
                Attach::Event(id) => assert!(event_index(id).is_some(), "{}", n.id),
                Attach::Person(id, page) => {
                    let p = person_index(id).unwrap_or_else(|| panic!("{}", n.id));
                    assert!(page < crate::talk::pages(p), "{}", n.id);
                }
            }
            for s in n.see {
                assert!(event_index(s).is_some(), "{} → {}", n.id, s);
            }
            assert!(n.q.ends_with('？'), "{}", n.id);
            assert!(!n.source.is_empty());
            // スマートフォンでも読める長さ
            assert!(n.a.chars().count() <= 260, "{} is too long", n.id);
        }
    }

    /// すべての時代で、すべての出来事と人物にノートがある
    #[test]
    fn every_event_and_person_has_notes() {
        for e in EVENTS {
            assert!(!for_event(e.id).is_empty(), "event {}", e.id);
        }
        for p in PEOPLE {
            assert!(!for_person_all(p.id).is_empty(), "person {}", p.id);
        }
    }
}
