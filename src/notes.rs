//! クロノの「なぜ？ノート」：場面を理解するために必要な背景を、子どもの疑問の形で用意する。
//!
//! 単語の意味ではなく、しくみ（パトロン・身分など）、理由（なぜそうしたのか）、
//! つながり（前後の出来事）、見方（立場による違い）を説明する。
//! ノートは出来事、または人物の話のページに結びつける。子どもは疑問を選んで押し、
//! クロノが答える。答えは小学生にもわかる言葉で漢字を使って書き（読み上げで補う）、
//! 言い切れないことは「〜と考えられている」と書く。
//!
use crate::history::*;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Attach {
    /// 出来事（id）
    Event(&'static str),
    /// 人物の話（id, ページ。会話のある人物では会話の場面の番号）
    Person(&'static str, usize),
}

pub struct Note {
    pub id: &'static str,
    pub attach: Attach,
    /// 子どもの疑問
    pub q: &'static str,
    /// クロノの答え
    pub a: &'static str,
    /// あわせて見たい出来事（id）
    pub see: &'static [&'static str],
    pub source: &'static str,
}

macro_rules! note {
    ($id:literal, $attach:expr, $q:literal, $a:literal, [$($see:literal),*], $src:literal) => {
        Note { id: $id, attach: $attach, q: $q, a: $a, see: &[$($see),*], source: $src }
    };
}

