/// 文に出てくる用語（出てくる順。長い書き方を先に照らし合わせ、重ならないようにする）
pub fn find(text: &str) -> Vec<usize> {
    let mut words: Vec<(usize, &str)> = TERMS
        .iter()
        .enumerate()
        .flat_map(|(i, t)| t.words.iter().map(move |w| (i, *w)))
        .collect();
    words.sort_by_key(|(_, w)| std::cmp::Reverse(w.len()));
    let mut taken = vec![false; text.len()];
    let mut hits: Vec<(usize, usize)> = vec![];
    for (i, w) in words {
        if hits.iter().any(|(k, _)| *k == i) {
            continue;
        }
        if let Some(at) = text
            .match_indices(w)
            .map(|(at, _)| at)
            .find(|at| !taken[*at..*at + w.len()].iter().any(|t| *t))
        {
            taken[at..at + w.len()].iter_mut().for_each(|t| *t = true);
            hits.push((i, at));
        }
    }
    hits.sort_by_key(|(_, at)| *at);
    hits.into_iter().map(|(i, _)| i).collect()
}

pub fn index(name: &str) -> Option<usize> {
    TERMS.iter().position(|t| t.name() == name)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::history::*;

    #[test]
    fn terms_are_unique_and_found() {
        let mut names: Vec<&str> = TERMS.iter().map(|t| t.name()).collect();
        names.sort();
        names.dedup();
        assert_eq!(names.len(), TERMS.len());
        for t in TERMS {
            assert!(!t.kid.is_empty() && !t.kana.is_empty());
        }
        // 長い書き方が優先され、短い用語が重ねて出ない
        let v = find("この年の初めには終身独裁官となった");
        assert_eq!(v, vec![index("独裁官").unwrap()]);
        let v = find("定子を皇后に、彰子を中宮とした");
        assert_eq!(v, vec![index("皇后").unwrap(), index("中宮").unwrap()]);
        assert!(!find("天皇").contains(&index("后").unwrap()));
    }

    /// どの用語も、ことばメモを出す文（人物の話・紹介、出来事、試練）のどこかに出てくる
    #[test]
    fn every_term_is_used() {
        let mut all = String::new();
        for p in PEOPLE {
            all += &p.lines.join("");
            all += p.bio;
            all += p.role;
        }
        for e in EVENTS {
            all += &e.body.join("");
        }
        for q in QUIZZES {
            all += q.q;
            all += &q.choices.join("");
            all += q.note;
        }
        let used = find(&all);
        for (i, t) in TERMS.iter().enumerate() {
            assert!(used.contains(&i), "unused term {}", t.name());
        }
    }
}
