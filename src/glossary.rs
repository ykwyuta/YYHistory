//! クロノの「ことばメモ」：人物の話や出来事に出てくる歴史の用語を、
//! 小学校低学年にもわかることばで説明する。
//!
//! words の最初が用語の名前（保存にも使う ID）。残りは同じ用語の別の書き方。
//! 説明は、ひらがなを中心にした短い文にする。正確さを優先し、
//! 言い切れないことは「〜と される」と書く。

pub struct Term {
    pub words: &'static [&'static str],
    pub kana: &'static str,
    pub kid: &'static str,
}

impl Term {
    pub fn name(&self) -> &'static str {
        self.words[0]
    }
}

macro_rules! term {
    ([$($w:literal),+], $kana:literal, $kid:literal) => {
        Term { words: &[$($w),+], kana: $kana, kid: $kid }
    };
}

